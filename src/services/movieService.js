// Get all unique genres from movies
export const getAllGenres = () => {
  const genresSet = new Set();
  MOVIES_DB.forEach(movie => {
    movie.genres.forEach(genre => genresSet.add(genre));
  });
  return Array.from(genresSet).sort();
};

// Filter movies by search query
export const searchMovies = (movies, query) => {
  if (!query) return movies;
  const lowerQuery = query.toLowerCase();
  return movies.filter(movie => 
    movie.title.toLowerCase().includes(lowerQuery) ||
    movie.description.toLowerCase().includes(lowerQuery) ||
    movie.genres.some(g => g.toLowerCase().includes(lowerQuery))
  );
};

// Filter movies by vibe
export const filterByVibe = (movies, vibe) => {
  if (!vibe) return movies;
  return movies.filter(movie => movie.vibe === vibe);
};

// Filter movies by genre
export const filterByGenre = (movies, genre) => {
  if (!genre) return movies;
  return movies.filter(movie => movie.genres.includes(genre));
};

// Calculate movie score based on user preferences
export const calculateRecommendationScore = (movie, userLikes, userRatings) => {
  let score = movie.rating || 0;
  
  // Boost score based on liked movies with similar genres
  const likedMovies = MOVIES_DB.filter(m => userLikes.includes(m.id));
  likedMovies.forEach(likedMovie => {
    const commonGenres = movie.genres.filter(g => likedMovie.genres.includes(g)).length;
    score += commonGenres * 0.5;
    
    if (movie.vibe === likedMovie.vibe) {
      score += 1;
    }
  });
  
  // Boost score based on highly rated movies with similar characteristics
  Object.entries(userRatings).forEach(([movieId, rating]) => {
    const ratedMovie = MOVIES_DB.find(m => m.id === parseInt(movieId));
    if (ratedMovie && rating >= 4) {
      const commonGenres = movie.genres.filter(g => ratedMovie.genres.includes(g)).length;
      score += commonGenres * (rating / 10);
      
      if (movie.vibe === ratedMovie.vibe) {
        score += rating / 5;
      }
    }
  });
  
  return score;
};

// Get recommended movies based on user preferences
export const getRecommendations = (userLikes, userRatings, watchlist, watchedMovies = []) => {
  // Don't recommend movies already in watchlist or watched
  const availableMovies = MOVIES_DB.filter(m => 
    !watchlist.includes(m.id) && !watchedMovies.includes(m.id)
  );
  
  // Calculate scores for each movie
  const scoredMovies = availableMovies.map(movie => ({
    ...movie,
    recommendationScore: calculateRecommendationScore(movie, userLikes, userRatings)
  }));
  
  // Sort by recommendation score and return top 50
  return scoredMovies
    .sort((a, b) => b.recommendationScore - a.recommendationScore)
    .slice(0, 50);
};

// Find similar movies based on genres and vibe
export const findSimilarMovies = (movieId, limit = 5) => {
  const sourceMovie = MOVIES_DB.find(m => m.id === movieId);
  if (!sourceMovie) return [];
  
  const otherMovies = MOVIES_DB.filter(m => m.id !== movieId);
  
  const scoredMovies = otherMovies.map(movie => {
    let similarityScore = 0;
    
    // Check genre overlap
    const commonGenres = movie.genres.filter(g => sourceMovie.genres.includes(g)).length;
    similarityScore += commonGenres * 2;
    
    // Check vibe match
    if (movie.vibe === sourceMovie.vibe) {
      similarityScore += 3;
    }
    
    // Check year proximity
    const yearDiff = Math.abs(movie.year - sourceMovie.year);
    if (yearDiff <= 5) {
      similarityScore += 1;
    }
    
    return { ...movie, similarityScore };
  });
  
  return scoredMovies
    .sort((a, b) => b.similarityScore - a.similarityScore)
    .slice(0, limit);
};

// Generate AI explanation for recommendation
export const generateAIExplanation = (movie, userLikes, userRatings, movieNotes = {}) => {
  const likedMovies = MOVIES_DB.filter(m => userLikes.includes(m.id));
  const highlyRatedMovies = Object.entries(userRatings)
    .filter(([_, rating]) => rating >= 4)
    .map(([id, _]) => MOVIES_DB.find(m => m.id === parseInt(id)))
    .filter(Boolean);
  
  if (likedMovies.length === 0 && highlyRatedMovies.length === 0) {
    return `${movie.title} is a highly-rated ${movie.genres.join('/')} film with a ${movie.vibe} vibe. It's a great choice for fans of quality cinema.`;
  }
  
  const relatedMovies = [...likedMovies, ...highlyRatedMovies];
  const commonGenres = movie.genres.filter(g => 
    relatedMovies.some(rm => rm.genres.includes(g))
  );
  
  const similarVibeMovies = relatedMovies.filter(rm => rm.vibe === movie.vibe);
  
  // Analyze user notes for preferences
  let noteInsights = '';
  const notesWithPositiveSentiment = Object.entries(movieNotes)
    .filter(([id, note]) => {
      const text = note.text.toLowerCase();
      return text.includes('love') || text.includes('funny') || text.includes('good') || 
             text.includes('great') || text.includes('excellent');
    })
    .map(([id, note]) => ({ 
      movie: MOVIES_DB.find(m => m.id === parseInt(id)),
      note: note.text
    }))
    .filter(item => item.movie);
  
  if (notesWithPositiveSentiment.length > 0) {
    const positiveGenres = [...new Set(notesWithPositiveSentiment.flatMap(item => item.movie.genres))];
    const matchingGenres = positiveGenres.filter(g => movie.genres.includes(g));
    
    if (matchingGenres.length > 0) {
      noteInsights = ` Your notes show you appreciate ${matchingGenres.join('/')} movies.`;
    }
  }
  
  let explanation = `Based on your preferences, ${movie.title} is recommended because `;
  
  if (commonGenres.length > 0 && similarVibeMovies.length > 0) {
    explanation += `you've enjoyed ${commonGenres.join('/')} films with a ${movie.vibe} vibe, particularly ${similarVibeMovies[0].title}.`;
  } else if (commonGenres.length > 0) {
    explanation += `you've shown interest in ${commonGenres.join('/')} films like ${relatedMovies[0].title}.`;
  } else if (similarVibeMovies.length > 0) {
    explanation += `it matches the ${movie.vibe} vibe of ${similarVibeMovies[0].title}, which you enjoyed.`;
  } else {
    explanation += `it's a critically acclaimed ${movie.genres.join('/')} film that aligns with your taste for quality cinema.`;
  }
  
  explanation += noteInsights;
  
  return explanation;
};
